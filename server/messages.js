const BY_KO = Object.fromEntries(Object.entries(MSG).map(([k, v]) => [v.ko, k]));
const fill = (t, p) => t.replace(/\{(\w+)\}/g, (_, k) => (p && k in p ? String(p[k]) : `{${k}}`));
// Build an error result: Korean text in `error`, plus key, params and English for i18n clients.
export function errOf(keyOrKo, params) {
  const key = MSG[keyOrKo] ? keyOrKo : BY_KO[keyOrKo];
  if (!key) return { error: String(keyOrKo), errorKey: null, errorParams: null, errorEn: String(keyOrKo) };
  return { error: fill(MSG[key].ko, params), errorKey: key, errorParams: params || null, errorEn: fill(MSG[key].en, params) };
}
